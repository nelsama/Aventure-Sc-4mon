def check(grid, name):
    if len(grid) != 16:
        raise SystemExit(f"{name}: {len(grid)} filas")
    for i, row in enumerate(grid):
        if len(row) != 16:
            raise SystemExit(f"{name} fila {i}: {len(row)} -> {row!r}")


def render(grid, pal, scale, bg=(35, 35, 48, 255)):
    img = Image.new("RGBA", (16, 16), bg)
    px = img.load()
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            px[x, y] = pal[ch]
    return img.resize((16 * scale, 16 * scale), Image.NEAREST)


def font(size):
    try:
        return ImageFont.load_default(size=size)
    except Exception:
        return ImageFont.load_default()


def sheet(rows, pal_rows, path, title, scale=10):
    """rows: [(label, grid), ...]; pal_rows: list of palettes (one per row)."""
    cell = 16 * scale
    gap_x = 28
    gap_y = 34
    margin = 24
    n = len(rows)
    w = margin * 2 + n * cell + (n - 1) * gap_x
    h = margin * 2 + 40 + len(pal_rows) * (cell + gap_y) + 26
    img = Image.new("RGBA", (w, h), (24, 24, 34, 255))
    d = ImageDraw.Draw(img)
    f = font(max(14, scale + 6))
    ft = font(max(18, scale + 10))
    d.text((margin, 10), title, font=ft, fill=(240, 220, 140, 255))
    for ri, pal in enumerate(pal_rows):
        y = margin + 40 + ri * (cell + gap_y)
        for ci, (label, grid) in enumerate(rows):
            x = margin + ci * (cell + gap_x)
            d.rectangle([x - 2, y - 2, x + cell + 1, y + cell + 1],
                        outline=(80, 80, 110, 255))
            img.paste(render(grid, pal, scale), (x, y), render(grid, pal, scale))
            d.text((x, y + cell + 5), label, font=f, fill=(225, 225, 235, 255))
    img.save(path)
    print(path, img.size)


def main():
    for name, g in PLAYERS + DRAGONS:
        check(g, name)
    sheet(PLAYERS, [P_PLAYER], "doc/player_options.png",
          "OPCIONES DE JUGADOR (16x16)", scale=12)
    sheet(DRAGONS, [P_RED, P_GREEN, P_GOLD], "doc/dragon_options.png",
          "OPCIONES DE DRAGON (16x16)", scale=10)
    return 0


